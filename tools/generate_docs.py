#!/usr/bin/env python3
"""Deterministic, offline schema-first reference documentation generator.

Commit generated files and run with --check in CI. Runtime semantics that
cannot be expressed in JSON Schema remain identified in the mapping records;
unreviewed legacy OVAL notes are printed only as non-normative candidates.
"""

import argparse
import difflib
from hashlib import sha256
import json
from pathlib import Path
import sys


PROJECT = Path(__file__).resolve().parents[1]
SCHEMAS = PROJECT / 'schema'
METADATA = PROJECT / 'docs' / 'metadata'
GENERATED = PROJECT / 'docs' / 'generated'
NOTICE = '<!-- Generated by tools/generate_docs.py. Do not hand-edit; CI checks exact bytes. -->'


def load(path):
    return json.loads(path.read_text(encoding='utf-8'))


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def markdown(value):
    return str(value).replace('|', r'\|').replace('\n', ' ').replace('\r', ' ').strip()


def entries_table(headers, rows):
    return ('| ' + ' | '.join(headers) + ' |\n'
            + '| ' + ' | '.join(['---'] * len(headers)) + ' |\n'
            + ''.join('| ' + ' | '.join(markdown(cell) for cell in row) + ' |\n'
                      for row in rows))


def frontmatter(heading, version):
    return (f'{NOTICE}\n\n# {heading} — {version}\n\n'
            'This is a **generated reference** from the frozen schema and capability '
            'metadata, not a statement of scanner implementation conformance. '
            'Pin the entire repository commit (or release tag when available), including '
            'documentation, schemas, specification and examples.\n\n')


def assessment_properties(schema):
    assessment = schema['properties']['assessment']
    tests = assessment['properties']['tests']['additionalProperties']
    rows = []
    for prefix, group in [('assessment', assessment),
                          ('assessment.tests.<test-id>', tests)]:
        required = set(group.get('required', []))
        for name, node in group.get('properties', {}).items():
            types = node.get('type', 'see $ref')
            if isinstance(types, list):
                types = ', '.join(types)
            rows.append((f'`{prefix}.{name}`', 'yes' if name in required else 'no',
                         f'`{types}`', node.get('title', ''), node.get('description', ''),
                         node.get('x-scap-ng-authoring', {}).get('control_id', '')))
    return rows


def render_schema_reference(version, roots, assessment):
    lines = [frontmatter('Structural schema reference', version),
             'The JSON Schema `$id` URIs retain their versioned `v0.4.1` '
             'identity. The physical repository layout is flat under `schema/`; '
             'resolvers should use the pinned release snapshot rather than '
             'fetching unversioned files over the network.\n\n',
             f'## Root schemas ({len(roots)})\n\n']
    rows = [(f'[`{path.name}`](../../schema/{path.name})',
             value.get('title', ''), value.get('description', ''))
            for path, value in roots]
    lines.extend([entries_table(['Schema', 'Title', 'Schema description'], rows),
                  '\n## Assessment and test authoring fields\n\n',
                  'These labels, structural types and descriptions are taken '
                  'directly from `assessment.schema.json`. A required structural '
                  'field is not necessarily a populated editor control.\n\n',
                  entries_table(['Path', 'Required', 'Type', 'Title', 'Description',
                                 'Editor control ID'], assessment_properties(assessment))])
    return ''.join(lines)


def mappings_inventory():
    records = []
    for classification in ('supported', 'experimental'):
        for path in sorted((SCHEMAS / 'capability-mappings' / classification).glob('*.json')):
            item = load(path)
            if item.get('capability') != path.stem:
                raise ValueError(f'{path}: capability and filename disagree')
            records.append((classification, path, item))
    return records


def render_capabilities(version, mappings, scope):
    expected = scope['supported']['expected_count']
    supported = sum(group == 'supported' for group, _, _ in mappings)
    if supported != expected:
        raise ValueError(f'supported capability count {supported} != {expected}')
    lines = [frontmatter('Capability contract catalog', version),
             f'## {supported} supported and {len(mappings) - supported} experimental mappings\n\n',
             'The frozen capability mapping metadata defines authoring selectors, '
             'collection parameters, result fields, datatypes and source lineage. '
             '**Supported** describes this specification catalog, not a qualified '
             'scanner provider. **Experimental** entries are not adopted as '
             'normative requirements.\n\n']
    rows = []
    for group, path, item in mappings:
        native = item.get('native', {})
        selectors = ', '.join(f'`{key}`' for key in native.get('selector_map', {})) or '—'
        fields = native.get('state_field_map', {})
        source = item.get('source', {})
        if not isinstance(source, dict):
            source = {}
        rows.append((f'[`{item["capability"]}`](../../schema/capability-mappings/{group}/{path.name})',
                     group, selectors, len(fields),
                     source.get('language', 'native metadata')))
    lines.append(entries_table(['Capability', 'Scope', 'Selectors', 'State fields',
                                'Source family'], rows))
    lines.append('\nSome capability metadata describes semantic validation rules '
                 'that Draft 2020-12 cannot enforce by itself. Implementers must '
                 'also apply the pinned semantic rules and qualification tests.\n')
    return ''.join(lines)


def render_scanner_catalog(version, mappings, coverage):
    """Every Assessment capability gets a section, even when evidence is absent."""
    records = coverage['records']
    names = {item['capability'] for _, _, item in mappings}
    if set(records) - names:
        raise ValueError('Orphan scanner guidance records: ' +
                         ', '.join(sorted(set(records) - names)))
    lines = [frontmatter('Scanner implementation guidance coverage', version),
             'Every known capability has a dedicated section, including '
             'capabilities with **documentation gaps**. These sections '
             'identify physical acquisition requirements separately from '
             'the Assessment authoring contract. Absence of scanner steps '
             'is an explicit gap, not permission for vendors to guess.\n\n']
    complete = sum(rec.get('status') == 'reviewed_qualified'
                   for rec in records.values())
    if complete:
        for name, rec in records.items():
            if rec.get('status') == 'reviewed_qualified' and not all(
                    rec.get(field) for field in coverage['required_for_qualified_guidance']):
                raise ValueError(f'{name}: qualified guidance missing approval evidence')
    lines.append(f'**Coverage:** {len(mappings)} capability sections; '
                 f'{complete} qualified guidance records, '
                 f'{len(mappings) - complete} pending full implementation guidance. '
                 'Qualification requires documented collection steps, '
                 'vendor/source references where applicable, missing/error '
                 'handling, conformance evidence and owner review.\n\n')
    summary = []
    for group, path, item in mappings:
        name = item['capability']
        record = records.get(name, {})
        status = record.get('status', 'documentation_gap')
        summary.append((f'[`{name}`](#' + name.replace('.', '') + ')', group,
                        f'`{status}`'))
    lines.append(entries_table(['Capability section', 'Scope', 'Scanner guidance'], summary))
    lines.append('\n## Per-capability implementation sections\n\n')
    for group, path, item in mappings:
        name = item['capability']
        record = records.get(name, {})
        native = item.get('native', {})
        status = record.get('status', 'documentation_gap')
        lines.append(f'### {name}\n\n')
        lines.append(f'**Guidance status:** `{status}`. '
                     f'**Contract:** [mapping](../../schema/capability-mappings/{group}/{path.name}).\n\n')
        selectors = ', '.join(f'`{field}`' for field in native.get('selector_map', {}))
        parameters = ', '.join(f'`{field}`' for field in native.get('collection_parameters', {}))
        fields = ', '.join(f'`{field}`' for field in sorted(set(native.get('state_field_map', {}).values())))
        lines.append(f'- Authoring selectors: {selectors or "none declared"}.\n')
        lines.append(f'- Collection parameters: {parameters or "none declared"}.\n')
        lines.append(f'- Returned/state fields: {fields or "none declared"}.\n')
        if record.get('reason'):
            lines.append(f'- Research status: {record["reason"]}\n')
        if record.get('semantic_research_ref'):
            family = name.split('.')[0]
            lines.append(f'- [Semantic research: native facts versus proposals](developer-contract-research-{family}.md#{name.replace(".", "")}).\n')
        steps = record.get('scanner_steps', [])
        if steps:
            lines.append('\n**Curated implementation steps:**\n\n')
            for num, step in enumerate(steps, 1):
                lines.append(f'{num}. {step}\n')
        else:
            lines.append('- **Implementation steps:** Not yet reviewed/documented.\n')
        references = record.get('source_references', [])
        if references:
            lines.append('\n**Source documentation:**\n\n')
            for ref in references:
                if not ref['url'].startswith('https://'):
                    raise ValueError(f'{name}: source reference must use HTTPS')
                lines.append(f'- [{ref["label"]}]({ref["url"]}) '
                             f'(`{ref["kind"]}`; not automatically normative)\n')
        else:
            lines.append('- **Vendor/source references:** Not yet reviewed/documented.\n')
        if name == 'windows.ntuser':
            lines.append('- [Legacy scanner research candidates](scanner-windows-ntuser.md) '
                         'are crosswalked but not yet promoted.\n')
        lines.append('\n')
    return ''.join(lines).rstrip() + '\n'


def render_developer_pilot(version, mappings, proposal):
    """Render author/scanner views from a shared frozen-contract model."""
    from developer_guide import render
    return render(version, mappings, proposal, frontmatter, entries_table)


def render_ntuser(version, mapping, notes, audit):
    if mapping['capability'] != notes['capability']:
        raise ValueError('NTUSER source notes do not match capability')
    native = mapping['native']
    fields = native['state_field_map']
    if set(fields) != set(notes['fields']):
        raise ValueError('NTUSER notes need exactly one entry per native field')
    if set(fields) != set(audit['nodes']['ntuser_item']['fields']):
        raise ValueError('NTUSER OVAL item audit does not cover all native fields')
    if set(fields) != set(audit['nodes']['ntuser_state']['fields']):
        raise ValueError('NTUSER OVAL state audit does not cover all native fields')
    if not native.get('post_alignment_ready'):
        raise ValueError('NTUSER mapping not marked post-alignment-ready')
    if notes['review_status'] != 'pending_native_equivalence_review':
        raise ValueError('Unreviewed OVAL notes cannot silently become normative')
    lines = [frontmatter('Windows NTUSER: authoring and scanner evidence', version),
             '**Normative boundary:** The current contract is the frozen '
             '[windows.ntuser capability mapping](../../schema/capability-mappings/supported/windows.ntuser.json) '
             'plus the 0.4 schemas. Legacy OVAL observations below are '
             '**review candidates only**, not new 0.4 rules or a qualified '
             'scanner implementation.\n\n',
             f'**Legacy review status:** `{notes["review_status"]}`. '
             'Source is OVAL 5.12.3. Original XSD license/disclaimer must '
             'accompany any later redistribution of verbatim XSD documentation. '
             'This repository stores paraphrased observations and cryptographic '
             'annotation inventories instead.\n\n',
             '## Native selectors\n\n']
    lines.append(entries_table(['Selector', 'OVAL object field'],
                               [(f'`{key}`', f'`{value}`')
                                for key, value in native['selector_map'].items()]))
    lines.append('\n**Native selector alternatives:** '
                 + ', '.join(', '.join(f'`{name}`' for name in group)
                             for group in native['object_selector_alternatives'])
                 + '. **Nullable selectors:** '
                 + ', '.join(f'`{name}`' for name in native['nullable_selectors'])
                 + '.\n\n## Collection parameters\n\n')
    lines.append(entries_table(['Parameter', 'Type', 'Required', 'Values',
                                'Contract description'],
                               [(f'`{name}`', f'`{info["type"]}`',
                                 'yes' if info.get('required') else 'no',
                                 ', '.join(map(str, info.get('enum', []))) or '—',
                                 info.get('description', ''))
                                for name, info in native['collection_parameters'].items()]))
    lines.append('\n## Collected/state fields and legacy research candidates\n\n')
    lines.append('Datatypes and enums in the first columns are frozen 0.4 '
                 'metadata. Source notes are paraphrased and still awaiting '
                 'native equivalence review.\n\n')
    rows = []
    for field, source_field in fields.items():
        types = ', '.join(f'`{x}`' for x in native['field_datatypes'][field])
        enums = ', '.join(f'`{x}`' for x in native.get('state_value_enums', {}).get(field, [])) or '—'
        node = audit['nodes']['ntuser_item']['fields'][field]
        rows.append((f'`{field}`', f'`{source_field}`', types, enums,
                     notes['fields'][field], node['annotation_count']))
    lines.append(entries_table(['Native field', 'Source item field', 'Datatype(s)',
                                'Allowed values (if constrained)',
                                'Legacy interpretation candidate',
                                'Source docs'], rows))
    lines.append('\n## Native semantic validator rules\n\n')
    for rule in mapping['semantic_validator_rules']:
        lines.append(f'- `{rule["id"]}`: {rule["rule"]}\n')
    lines.append('\n## Historical scanner implementation evidence (not adopted)\n\n')
    for observation in notes['scanner_observations']:
        if observation['source_node'] not in audit['nodes']:
            raise ValueError('Unknown OVAL scanner observation source node')
        lines.append(f'- **{observation["id"].replace("_", " ").capitalize()}** '
                     f'(OVAL `{observation["source_node"]}`): '
                     f'{observation["summary"]}\n')
    lines.append('\n## Provenance and review audit\n\n')
    lines.append('The source inventory covers these XSD elements, documenting '
                 'counts and SHA-256 fingerprints of whitespace-normalized '
                 'annotations without incorporating the original licensed prose. '
                 'Re-run `tools/harvest_oval_ntuser.py` with the original pinned '
                 'XSD files when auditing source changes.\n\n')
    lines.append(entries_table(['XSD node', 'Documentation nodes',
                                'Normalized characters', 'Annotation SHA-256'],
                               [(f'`{name}`', data['annotation_count'],
                                 data['normalized_characters'],
                                 f'`{data["normalized_sha256"]}`')
                                for name, data in audit['nodes'].items()]))
    lines.append('\n')
    for category, identity in audit['files'].items():
        lines.append(f'- {category.replace("_", " ")}: '
                     f'[OVAL 5.12.3 XSD]({identity["upstream_url"]}), '
                     f'Git blob `{identity["git_blob_sha1"]}`, '
                     f'SHA-256 `{identity["sha256"]}`.\n')
    lines.append('\n**Do not infer** implementation qualification, equivalent '
                 'collection error behavior, Windows case-comparison defaults, '
                 'or native result semantics from this OVAL lineage alone. '
                 'Evidence of equivalence must be reviewed and recorded before '
                 'any candidate note becomes a normative scanner requirement.\n')
    return ''.join(lines)


def generated_documents():
    roots = [(path, load(path)) for path in sorted(SCHEMAS.glob('*.schema.json'))]
    if len(roots) != 35:
        raise ValueError('Frozen root schema count changed')
    version = load(SCHEMAS / 'assessment.schema.json')['x-scap-ng-version']
    scope = load(SCHEMAS / 'capability-scope.json')
    mappings = mappings_inventory()
    notes = load(METADATA / 'windows.ntuser-source-notes.json')
    audit = load(METADATA / 'windows.ntuser-oval-audit.json')
    coverage = load(METADATA / 'scanner-guidance-status.json')
    proposal = load(METADATA / 'schema-documentation-pilot.json')
    ntuser = next(item for group, _, item in mappings
                  if group == 'supported' and item['capability'] == 'windows.ntuser')
    md_files = {
        'schema-reference.md': render_schema_reference(version, roots,
                                                       load(SCHEMAS / 'assessment.schema.json')),
        'capability-catalog.md': render_capabilities(version, mappings, scope),
        'scanner-implementation-catalog.md': render_scanner_catalog(
            version, mappings, coverage),
        'scanner-windows-ntuser.md': render_ntuser(version, ntuser, notes, audit),
    }
    md_files.update(render_developer_pilot(version, mappings, proposal))
    from render_contract_research import render as render_research
    md_files.update(render_research(version, frontmatter, entries_table))
    immutable = sorted((*SCHEMAS.glob('*.json'),
                        *(SCHEMAS / 'capability-mappings').rglob('*.json')))
    fingerprint = sha256()
    for path in immutable:
        fingerprint.update(path.relative_to(SCHEMAS).as_posix().encode() + b'\0')
        fingerprint.update(path.read_bytes())
    if len(immutable) != 145:
        raise ValueError('Active 0.4.1 schema file count changed; regenerate and qualify an updated release pin')
    manifest = {
        'format': 'scap-ng/schema-documentation-drift-audit/1',
        'version': version,
        'schema_root': 'schema/',
        'release_boundary': 'entire repository tree at a specific commit or release tag',
        'frozen_json_count': len(immutable),
        'frozen_json_aggregate_sha256': fingerprint.hexdigest(),
        'source_metadata_sha256': {
            path.name: digest(path)
            for path in sorted(METADATA.glob('*.json'))
        },
        'legacy_oval_status': notes['review_status'],
        'generated_sha256': {
            name: sha256(value.encode('utf-8')).hexdigest()
            for name, value in sorted(md_files.items())
        },
        'method': 'offline deterministic generation; exact-byte --check enforced in CI',
    }
    return {**md_files, 'documentation-audit.json':
            json.dumps(manifest, indent=2, ensure_ascii=False) + '\n'}


def verify_documents(expected, output_dir):
    """Return exact-byte drift details; pure so tests can exercise tampering."""
    failures = {}
    for filename, content in expected.items():
        path = output_dir / filename
        raw = path.read_bytes() if path.exists() else None
        actual = raw.decode('utf-8', errors='replace') if raw is not None else ''
        if raw != content.encode('utf-8'):
            failures[filename] = '\n'.join(list(difflib.unified_diff(
                actual.splitlines(), content.splitlines(), fromfile='committed',
                tofile='expected', lineterm=''))[:24])
    return failures


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='Fail if checked-in generated docs differ (CI mode)')
    args = parser.parse_args()
    expected = generated_documents()
    if args.check:
        failures = verify_documents(expected, GENERATED)
        for filename, detail in failures.items():
            print(f'Out of date: docs/generated/{filename}', file=sys.stderr)
            print(detail, file=sys.stderr)
        if failures:
            raise SystemExit(f'{len(failures)} generated documentation files drifted')
        print(f'Exact-byte documentation drift check passed ({len(expected)} files)')
    else:
        GENERATED.mkdir(parents=True, exist_ok=True)
        for filename, content in expected.items():
            (GENERATED / filename).write_text(content, encoding='utf-8', newline='\n')
        print(f'Generated {len(expected)} documentation files from active 0.4.1 metadata')


if __name__ == '__main__':
    main()
