#!/usr/bin/env python3
"""Build a unified SCAP 1.4 benchmark IR from a source datastream and rule OVAL IR.

The IR joins XCCDF policy/profile/value/check semantics to the faithful per-rule
OVAL semantic IR generated by tools/oval_semantic_ir.py. It preserves complete
XCCDF rule subtrees for loss accounting while exposing normalized fields needed
by SCAP-NG renderers.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Iterable

from lxml import etree

import scap14_rule_splitter as split


def text_content(element) -> str | None:
    value = " ".join("".join(element.itertext()).split())
    return value or None


def child_text(element, name: str) -> str | None:
    for child in element:
        if isinstance(child.tag, str) and split.local(child.tag) == name:
            return text_content(child)
    return None


def child_texts(element, name: str) -> list[str]:
    return [
        text_content(child)
        for child in element
        if isinstance(child.tag, str)
        and split.local(child.tag) == name
        and text_content(child) is not None
    ]


def idrefs(element, name: str) -> list[str]:
    out=[]
    for child in element:
        if not isinstance(child.tag,str) or split.local(child.tag)!=name:
            continue
        value=child.get("idref") or text_content(child)
        if value:
            out.append(value)
    return out


def requires_conditions(element) -> list[list[str]]:
    """Preserve XCCDF requires grouping: OR within an element, AND across elements."""
    out=[]
    for raw in idrefs(element,"requires"):
        refs=[x for x in raw.split() if x]
        if refs:
            out.append(refs)
    return out


def boolean_attribute(value, default=None):
    if value is None:
        return default
    return str(value).strip().lower() in {"1","true"}


def references(element) -> list[dict]:
    out = []
    for child in element:
        if not isinstance(child.tag, str) or split.local(child.tag) != "reference":
            continue
        out.append({
            "href": child.get("href") or child.get("{http://www.w3.org/1999/xlink}href"),
            "text": text_content(child),
        })
    return out


def idents(element) -> list[dict]:
    out = []
    for child in element:
        if not isinstance(child.tag, str) or split.local(child.tag) != "ident":
            continue
        out.append({
            "system": child.get("system"),
            "value": text_content(child),
        })
    return out


def platforms(element) -> list[str]:
    return [
        child.get("idref")
        for child in element
        if isinstance(child.tag, str)
        and split.local(child.tag) == "platform"
        and child.get("idref")
    ]


def checks(element) -> list[dict]:
    rows = []
    for check in element:
        if not isinstance(check.tag, str) or split.local(check.tag) != "check":
            continue
        exports = []
        refs = []
        for node in check.iter():
            if not isinstance(node.tag, str):
                continue
            name = split.local(node.tag)
            if name == "check-export":
                exports.append({
                    "export_name": node.get("export-name"),
                    "value_id": node.get("value-id"),
                })
            elif name == "check-content-ref":
                refs.append({
                    "name": node.get("name"),
                    "href": node.get("href") or node.get("{http://www.w3.org/1999/xlink}href"),
                })
        rows.append({
            "system": check.get("system"),
            "selector": check.get("selector"),
            "negate": check.get("negate"),
            "multi_check": check.get("multi-check"),
            "exports": exports,
            "content_refs": refs,
            "inline_content": next(
                (
                    text_content(node)
                    for node in check
                    if isinstance(node.tag, str)
                    and split.local(node.tag) == "check-content"
                ),
                None,
            ),
            "source_tree": split.xccdf_node(check),
        })
    return rows


def fix_entries(rule) -> list[dict]:
    rows = []
    for child in rule:
        if not isinstance(child.tag, str):
            continue
        name = split.local(child.tag)
        if name not in {"fix", "fixtext"}:
            continue
        rows.append({
            "kind": name,
            "id": child.get("id"),
            "system": child.get("system"),
            "strategy": child.get("strategy"),
            "reboot": child.get("reboot"),
            "disruption": child.get("disruption"),
            "complexity": child.get("complexity"),
            "text": text_content(child),
            "source_tree": split.xccdf_node(child),
        })
    return rows


def effective_platform_refs(element, inherited: list[str]) -> list[str]:
    own=platforms(element)
    return own if own else list(inherited)


def rule_semantics(rule, group_path: list[str], inherited_platforms: list[str]) -> dict:
    return {
        "id": rule.get("id"),
        "title": child_text(rule, "title"),
        "description": child_text(rule, "description"),
        "rationale": child_text(rule, "rationale"),
        "severity": rule.get("severity"),
        "weight": rule.get("weight"),
        "role": rule.get("role"),
        "selected": rule.get("selected"),
        "selected_default": boolean_attribute(rule.get("selected"), True),
        "cluster_id": rule.get("cluster-id"),
        "extends": rule.get("extends"),
        "abstract": boolean_attribute(rule.get("abstract"), False),
        "hidden": boolean_attribute(rule.get("hidden"), False),
        "prohibit_changes": boolean_attribute(rule.get("prohibitChanges"), False),
        "multiple": boolean_attribute(rule.get("multiple"), False),
        "group_path": list(group_path),
        "platforms": platforms(rule),
        "effective_platform_refs": effective_platform_refs(rule,inherited_platforms),
        "requires": requires_conditions(rule),
        "conflicts": idrefs(rule, "conflicts"),
        "idents": idents(rule),
        "references": references(rule),
        "checks": checks(rule),
        "fixes": fix_entries(rule),
        "source_tree": split.xccdf_node(rule),
    }


def walk_rules(
    node,
    group_path: list[str] | None = None,
    inherited_platforms: list[str] | None = None,
) -> Iterable[dict]:
    group_path = list(group_path or [])
    inherited_platforms=list(inherited_platforms or [])
    for child in node:
        if not isinstance(child.tag, str):
            continue
        name = split.local(child.tag)
        if name == "Group":
            gid = child.get("id") or child_text(child, "title") or "unnamed-group"
            group_platforms=effective_platform_refs(child,inherited_platforms)
            yield from walk_rules(
                child,
                group_path + [gid],
                group_platforms,
            )
        elif name == "Rule":
            yield rule_semantics(child, group_path, inherited_platforms)


def group_semantics(
    group,
    parent_path: list[str],
    inherited_platforms: list[str],
) -> dict:
    gid=group.get("id")
    current_path=parent_path+([gid] if gid else [])
    child_groups=[]
    child_rules=[]
    child_values=[]
    for child in group:
        if not isinstance(child.tag,str):
            continue
        name=split.local(child.tag)
        if name=="Group" and child.get("id"):
            child_groups.append(child.get("id"))
        elif name=="Rule" and child.get("id"):
            child_rules.append(child.get("id"))
        elif name=="Value" and child.get("id"):
            child_values.append(child.get("id"))
    return {
        "id":gid,
        "title":child_text(group,"title"),
        "description":child_text(group,"description"),
        "rationale":child_text(group,"rationale"),
        "parent_path":list(parent_path),
        "path":current_path,
        "selected":group.get("selected"),
        "selected_default":boolean_attribute(group.get("selected"),True),
        "cluster_id":group.get("cluster-id"),
        "extends":group.get("extends"),
        "abstract":boolean_attribute(group.get("abstract"),False),
        "hidden":boolean_attribute(group.get("hidden"),False),
        "prohibit_changes":boolean_attribute(group.get("prohibitChanges"),False),
        "weight":group.get("weight"),
        "platforms":platforms(group),
        "effective_platform_refs":effective_platform_refs(group,inherited_platforms),
        "requires":requires_conditions(group),
        "conflicts":idrefs(group,"conflicts"),
        "references":references(group),
        "attributes":{
            etree.QName(k).localname:v for k,v in group.attrib.items()
        },
        "members":{
            "groups":child_groups,
            "rules":child_rules,
            "values":child_values,
        },
        "source_tree":split.xccdf_node(group),
    }


def walk_groups(
    node,
    parent_path: list[str] | None=None,
    inherited_platforms: list[str] | None=None,
):
    parent_path=list(parent_path or [])
    inherited_platforms=list(inherited_platforms or [])
    for child in node:
        if not isinstance(child.tag,str) or split.local(child.tag)!="Group":
            continue
        row=group_semantics(child,parent_path,inherited_platforms)
        yield row
        yield from walk_groups(
            child,
            row["path"],
            row["effective_platform_refs"],
        )


def walk_values(node, group_path: list[str] | None=None):
    group_path=list(group_path or [])
    for child in node:
        if not isinstance(child.tag,str):
            continue
        name=split.local(child.tag)
        if name=="Value":
            yield value_semantics(child,group_path)
        elif name=="Group":
            gid=child.get("id")
            yield from walk_values(child,group_path+([gid] if gid else []))


def value_semantics(value, group_path: list[str] | None=None) -> dict:
    choices = []
    defaults = []
    for child in value:
        if not isinstance(child.tag, str):
            continue
        name = split.local(child.tag)
        if name == "value":
            defaults.append({
                "selector": child.get("selector"),
                "value": text_content(child),
            })
        elif name == "choices":
            for choice in child:
                if isinstance(choice.tag, str) and split.local(choice.tag) == "choice":
                    choices.append({
                        "selector": choice.get("selector"),
                        "value": text_content(choice),
                    })
    return {
        "id": value.get("id"),
        "title": child_text(value, "title"),
        "description": child_text(value, "description"),
        "type": value.get("type"),
        "operator": value.get("operator"),
        "interactive": value.get("interactive"),
        "cluster_id": value.get("cluster-id"),
        "extends": value.get("extends"),
        "abstract": boolean_attribute(value.get("abstract"),False),
        "hidden": boolean_attribute(value.get("hidden"),False),
        "prohibit_changes": boolean_attribute(value.get("prohibitChanges"),False),
        "group_path":list(group_path or []),
        "attributes":{
            etree.QName(k).localname:v for k,v in value.attrib.items()
        },
        "defaults": defaults,
        "choices": choices,
        "source_tree": split.xccdf_node(value),
    }


def profile_semantics(profile) -> dict:
    actions = []
    for child in profile:
        if not isinstance(child.tag, str):
            continue
        name = split.local(child.tag)
        if name in {"select", "set-value", "set-complex-value", "refine-value", "refine-rule"}:
            actions.append({
                "kind": name,
                "attributes": {
                    etree.QName(k).localname: v for k, v in child.attrib.items()
                },
                "value": text_content(child),
                "source_tree": split.xccdf_node(child),
            })
    return {
        "id": profile.get("id"),
        "title": child_text(profile, "title"),
        "description": child_text(profile, "description"),
        "extends": profile.get("extends"),
        "abstract":profile.get("abstract"),
        "prohibit_changes":profile.get("prohibitChanges"),
        "platforms":platforms(profile),
        "references":references(profile),
        "version":child_text(profile,"version"),
        "actions": actions,
        "source_tree": split.xccdf_node(profile),
    }


def cpe_expression(node) -> dict:
    name=split.local(node.tag)
    if name=="logical-test":
        return {
            "kind":"logical_test",
            "operator":node.get("operator"),
            "negate":boolean_attribute(node.get("negate"),False),
            "children":[
                cpe_expression(child)
                for child in node
                if isinstance(child.tag,str)
                and split.local(child.tag) in {"logical-test","fact-ref","check-fact-ref"}
            ],
        }
    if name=="fact-ref":
        return {
            "kind":"cpe_name",
            "name":node.get("name"),
        }
    if name=="check-fact-ref":
        return {
            "kind":"check_fact",
            "system":node.get("system"),
            "href":node.get("href"),
            "id_ref":node.get("id-ref"),
        }
    return {
        "kind":"preserved_unknown_cpe_node",
        "source_tree":split.xccdf_node(node),
    }


def cpe_platform_definitions(benchmark) -> list[dict]:
    out=[]
    for spec in benchmark:
        if not isinstance(spec.tag,str) or split.local(spec.tag)!="platform-specification":
            continue
        for platform in spec:
            if not isinstance(platform.tag,str) or split.local(platform.tag)!="platform":
                continue
            logical=next(
                (
                    child for child in platform
                    if isinstance(child.tag,str) and split.local(child.tag)=="logical-test"
                ),
                None,
            )
            out.append({
                "id":platform.get("id"),
                "titles":[
                    {
                        "lang":child.get("{http://www.w3.org/XML/1998/namespace}lang"),
                        "text":text_content(child),
                    }
                    for child in platform
                    if isinstance(child.tag,str) and split.local(child.tag)=="title"
                ],
                "remarks":[
                    text_content(child)
                    for child in platform
                    if isinstance(child.tag,str) and split.local(child.tag)=="remark"
                ],
                "expression":cpe_expression(logical) if logical is not None else None,
                "source_tree":split.xccdf_node(platform),
            })
    return out


def bind_platform_refs(refs: list[str], definitions: list[dict]) -> list[dict]:
    by_id={x["id"]:x for x in definitions if x.get("id")}
    out=[]
    for ref in refs:
        local_id=ref[1:] if ref.startswith("#") else None
        if local_id and local_id in by_id:
            out.append({
                "ref":ref,
                "kind":"local_cpe_expression",
                "platform_id":local_id,
                "expression":by_id[local_id].get("expression"),
            })
        else:
            out.append({
                "ref":ref,
                "kind":"cpe_name",
                "name":ref,
            })
    return out


def resolve_profiles(profiles: list[dict], rules: list[dict], groups: list[dict], values: list[dict]) -> list[dict]:
    """Resolve XCCDF profile extension and expand selector targets without flattening traversal semantics.

    XCCDF 1.2 appends inherited selectors before the extending profile's own
    selectors. The effective action sequence is therefore parent actions first,
    child actions last. Target expansion understands direct ids and cluster-id
    membership but leaves requires/conflicts and group traversal to the policy
    processing plan.
    """
    by_profile={p["id"]:p for p in profiles if p.get("id")}
    item_sets={
        "rule":rules,
        "group":groups,
        "value":values,
    }

    def target_rows(action):
        idref=action.get("attributes",{}).get("idref")
        if not idref:
            return [],"missing_idref"
        kinds=(
            ("rule","group")
            if action["kind"] in {"select","refine-rule"}
            else ("value",)
        )
        direct=[]
        clustered=[]
        for kind in kinds:
            for row in item_sets[kind]:
                if row.get("id")==idref:
                    direct.append({"kind":kind,"id":row["id"],"match":"id"})
                if row.get("cluster_id")==idref:
                    clustered.append({"kind":kind,"id":row["id"],"match":"cluster-id"})
        if direct and clustered:
            return direct+clustered,"ambiguous_id_and_cluster"
        targets=direct or clustered
        return targets,("resolved" if targets else "unresolved_idref")

    cache={}
    stack=[]

    def resolve(pid):
        if pid in cache:
            return cache[pid]
        if pid in stack:
            cycle=stack[stack.index(pid):]+[pid]
            raise ValueError("profile extends cycle: "+" -> ".join(cycle))
        profile=by_profile.get(pid)
        if profile is None:
            raise ValueError(f"profile extends unknown profile: {pid}")
        stack.append(pid)
        chain=[]
        inherited=[]
        if profile.get("extends"):
            parent=resolve(profile["extends"])
            chain.extend(parent["inheritance_chain"])
            inherited.extend(parent["effective_actions"])
        chain.append(pid)
        own=[]
        for action in profile.get("actions",[]):
            expanded=dict(action)
            targets,status=target_rows(action)
            expanded["source_profile_id"]=pid
            expanded["targets"]=targets
            expanded["target_resolution"]=status
            own.append(expanded)
        effective=[dict(a) for a in inherited]+own
        for index,action in enumerate(effective):
            action["effective_order"]=index
        unresolved=[
            {
                "effective_order":a["effective_order"],
                "kind":a["kind"],
                "idref":a.get("attributes",{}).get("idref"),
                "status":a.get("target_resolution"),
            }
            for a in effective
            if a.get("target_resolution")!="resolved"
        ]
        result={
            "id":pid,
            "extends":profile.get("extends"),
            "inheritance_chain":chain,
            "effective_actions":effective,
            "resolution_status":"resolved" if not unresolved else "requires_review",
            "unresolved_targets":unresolved,
        }
        cache[pid]=result
        stack.pop()
        return result

    return [resolve(p["id"]) for p in profiles if p.get("id")]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def load_rule_ir(split_root: Path, manifest: dict) -> tuple[dict, dict]:
    by_rule = {}
    diagnostics = {}
    for row in manifest.get("rules", []):
        rid = row.get("rule_id")
        if not rid:
            continue
        diagnostics[rid] = row
        if row.get("status") != "split_valid":
            continue
        ir_path = split_root / Path(row["path"]).parent / "oval-ir.json"
        if not ir_path.exists():
            raise FileNotFoundError(f"missing OVAL IR for {rid}: {ir_path}")
        by_rule[rid] = json.loads(ir_path.read_text(encoding="utf-8"))
    return by_rule, diagnostics


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("source_zip", type=Path)
    ap.add_argument("--split-root", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()

    member, ds_bytes, ds_root = split.find_datastream(args.source_zip)
    components, _ = split.embedded_components(ds_root)
    benchmarks = [
        (cid, root) for cid, root in components.items()
        if split.component_kind(root) == "xccdf"
    ]
    if len(benchmarks) != 1:
        raise ValueError(
            f"expected exactly one embedded XCCDF Benchmark, found {len(benchmarks)}"
        )

    manifest_path = args.split_root / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    oval_ir, split_diag = load_rule_ir(args.split_root, manifest)

    component_id, benchmark = benchmarks[0]
    benchmark_platform_refs=platforms(benchmark)
    platform_definitions=cpe_platform_definitions(benchmark)
    rules = list(walk_rules(
        benchmark,
        inherited_platforms=benchmark_platform_refs,
    ))
    groups=list(walk_groups(
        benchmark,
        inherited_platforms=benchmark_platform_refs,
    ))
    values=list(walk_values(benchmark))
    profiles = [
        profile_semantics(e) for e in benchmark.iter()
        if isinstance(e.tag, str) and split.local(e.tag) == "Profile"
    ]
    for profile in profiles:
        profile["effective_platform_refs"]=(
            profile["platforms"] if profile["platforms"] else list(benchmark_platform_refs)
        )
        profile["effective_platforms"]=bind_platform_refs(
            profile["effective_platform_refs"],platform_definitions
        )
    for rule in rules:
        rule["effective_platforms"]=bind_platform_refs(
            rule["effective_platform_refs"],platform_definitions
        )
    for group in groups:
        group["effective_platforms"]=bind_platform_refs(
            group["effective_platform_refs"],platform_definitions
        )
    resolved_profiles=resolve_profiles(profiles,rules,groups,values)

    joined_rules = []
    missing_manifest = []
    for rule in rules:
        rid = rule["id"]
        diag = split_diag.get(rid)
        if diag is None:
            missing_manifest.append(rid)
        assessment = None
        if rid in oval_ir:
            assessment = {
                "kind": "oval_semantic_ir",
                "ir": oval_ir[rid],
            }
        elif diag:
            assessment = {
                "kind": "manual_or_external",
                "split_status": diag.get("status"),
                "checks": diag.get("checks", rule.get("checks", [])),
            }
        joined_rules.append({
            **rule,
            "assessment_source": assessment,
            "split_diagnostic": diag,
        })

    if missing_manifest:
        raise ValueError(
            f"{len(missing_manifest)} XCCDF rules missing from split manifest: "
            + ", ".join(missing_manifest[:10])
        )

    out = {
        "format": "scap-ng-scap14-benchmark-ir-0.1",
        "source": {
            "zip": args.source_zip.name,
            "zip_sha256": sha256_file(args.source_zip),
            "datastream_member": member,
            "datastream_sha256": hashlib.sha256(ds_bytes).hexdigest(),
            "split_manifest": manifest.get("source"),
        },
        "benchmark": {
            "component_id": component_id,
            "id": benchmark.get("id"),
            "title": child_text(benchmark, "title"),
            "description": child_text(benchmark, "description"),
            "version": child_text(benchmark, "version"),
            "status": [
                {
                    "date": child.get("date"),
                    "value": text_content(child),
                }
                for child in benchmark
                if isinstance(child.tag, str) and split.local(child.tag) == "status"
            ],
            "platforms": benchmark_platform_refs,
            "effective_platforms": bind_platform_refs(
                benchmark_platform_refs,platform_definitions
            ),
            "references": references(benchmark),
            "rule_count": len(rules),
            "profile_count": len(profiles),
            "value_count": len(values),
            "group_count": len(groups),
            "source_tree": split.xccdf_node(benchmark),
        },
        "platform_definitions":platform_definitions,
        "profiles": profiles,
        "resolved_profiles": resolved_profiles,
        "values": values,
        "groups": groups,
        "rules": joined_rules,
        "summary": {
            "rules": len(joined_rules),
            "groups":len(groups),
            "platform_definitions":len(platform_definitions),
            "local_platform_refs":sum(
                1 for ref in benchmark_platform_refs if ref.startswith("#")
            ),
            "profiles":len(profiles),
            "resolved_profiles":len(resolved_profiles),
            "profile_resolution_requires_review":sum(
                1 for x in resolved_profiles if x["resolution_status"]!="resolved"
            ),
            "values":len(values),
            "rules_with_oval_ir": sum(
                1 for x in joined_rules
                if x["assessment_source"]
                and x["assessment_source"]["kind"] == "oval_semantic_ir"
            ),
            "rules_manual_or_external": sum(
                1 for x in joined_rules
                if x["assessment_source"]
                and x["assessment_source"]["kind"] == "manual_or_external"
            ),
            "missing_manifest_rules": len(missing_manifest),
        },
    }

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(out, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(out["summary"], indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
