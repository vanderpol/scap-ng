#!/usr/bin/env python3
"""Verify historical documentation receipts without loading them as 0.4.1.

Issue #40/43 artifacts intentionally retain their 0.4.0 URIs and source bytes.
This verifier resolves each recorded file through Git at its recorded source
commit. It never validates those files against the active schema directory.
"""
from argparse import ArgumentParser
from hashlib import sha256
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
ISSUE40 = ROOT / 'docs/research/issue40'
PACK = ROOT / 'docs/review-packs/issue43-phase-a'
NATIVE = '63110e7762f4963d3e4d407e90b9fcfd9cfe86ad'
PR39 = 'f61fff037f18832aa04db140b3e3209dfddf7219'
PR41 = '532fbbfe52a220d2672256ac54d1e117d69cd043'


def git_bytes(commit, path):
    return subprocess.check_output(['git', '-C', str(ROOT), 'show', f'{commit}:{path}'], stderr=subprocess.DEVNULL)


def digest(raw):
    return sha256(raw).hexdigest()


def verify():
    checked = []
    manifest = json.loads((ISSUE40 / 'schema-manifest.json').read_text())
    if manifest['native_commit'] != NATIVE:
        raise ValueError('Issue #40 native commit drifted')
    for row in manifest['files']:
        raw = git_bytes(NATIVE, row['file'])
        if digest(raw) != row['sha256']:
            raise ValueError('Issue #40 source receipt drifted: ' + row['file'])
        checked.append({'path': row['file'], 'commit': NATIVE, 'sha256': row['sha256']})

    pins = json.loads((PACK / 'input-pins.json').read_text())
    if pins['source_commits'] != {'native': NATIVE, 'pr39': PR39, 'pr41': PR41}:
        raise ValueError('Issue #43 source commit pins drifted')
    for path, expected in pins['files'].items():
        matches = []
        for label, commit in pins['source_commits'].items():
            try:
                raw = git_bytes(commit, path)
            except subprocess.CalledProcessError:
                continue
            if digest(raw) == expected:
                matches.append({'label': label, 'commit': commit})
        if not matches:
            # Some review-only helper files were generated by an earlier
            # historical commit than the three semantic source pins. Resolve
            # that exact Git blob without treating it as current evidence.
            commits = subprocess.check_output(
                ['git', '-C', str(ROOT), 'log', '--all', '--format=%H', '--', path], text=True).split()
            for commit in commits:
                try:
                    raw = git_bytes(commit, path)
                except subprocess.CalledProcessError:
                    continue
                if digest(raw) == expected:
                    matches.append({'label': 'historical-file-commit', 'commit': commit})
                    break
        if not matches:
            raise ValueError('Issue #43 source receipt drifted: ' + path)
        checked.append({'path': path, 'sha256': expected, 'matches': matches})

    notes = json.loads((ISSUE40 / 'review-notes.json').read_text())
    historical_uris = sum(
        1 for proposal in notes['proposals']
        if proposal['schema_uri'].startswith('https://scap-ng.dev/schema/v0.4.0/'))
    if historical_uris != len(notes['proposals']):
        raise ValueError('historical review notes contain a non-0.4.0 URI')
    pack_manifest = json.loads((PACK / 'manifest.json').read_text())
    for uri, row in pack_manifest['resources'].items():
        relative = row['file']
        raw = (PACK / relative).read_bytes()
        if digest(raw) != row['sha256']:
            raise ValueError('review-pack resource receipt drifted: ' + relative)
    return {
        'format': 'scap-ng-historical-documentation-receipt-1',
        'schema_version': '0.4.0',
        'issue40_native_commit': NATIVE,
        'issue43_source_commits': pins['source_commits'],
        'issue40_review_notes': len(notes['proposals']),
        'issue40_schema_files': len(manifest['files']),
        'issue43_pinned_inputs': len(pins['files']),
        'issue43_pack_resources': len(pack_manifest['resources']),
        'active_schema_checked': False,
        'historical_sources_checked': len(checked),
        'status': 'PASS',
    }


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--write-receipt', action='store_true')
    args = parser.parse_args()
    try:
        receipt = verify()
        target = ISSUE40 / 'HISTORICAL-RECEIPT.json'
        if args.write_receipt:
            target.write_text(json.dumps(receipt, indent=2, sort_keys=True) + '\n')
        elif args.check and (not target.exists() or json.loads(target.read_text()) != receipt):
            raise ValueError('historical receipt is stale: ' + str(target.relative_to(ROOT)))
        print(json.dumps(receipt, sort_keys=True))
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print('Historical documentation verification: ' + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
